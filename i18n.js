  function t(key, p) {
    const v = key in dict[lang] ? dict[lang][key] : key in ru ? ru[key] : key;
    if (typeof v === 'function') return v(p || {});
    if (!p) return v;
    return v.replace(/\{(\w+)\}/g, (m, k) => (p[k] != null ? p[k] : m));
  }

